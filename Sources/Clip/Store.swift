import AppKit
import CryptoKit
import ImageIO

struct Item: Codable, Identifiable, Equatable {
    let id: UUID
    var text: String
    var date: Date
    var pinned: Bool
    /// Nome do PNG em `images/`; nil para itens de texto.
    var imageFile: String?
    /// SHA-256 do PNG, usado para deduplicar imagens.
    var imageHash: String?

    var isImage: Bool { imageFile != nil }
}

final class HistoryStore: ObservableObject {
    @Published private(set) var items: [Item] = []

    private let dir: URL
    private let imagesDir: URL
    private let fileURL: URL
    private let limit = 200
    private var lastChange = NSPasteboard.general.changeCount
    private let thumbnails = NSCache<NSString, NSImage>()
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Clip", isDirectory: true)
        imagesDir = dir.appendingPathComponent("images", isDirectory: true)
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")
        if let data = try? Data(contentsOf: fileURL),
           let saved = try? JSONDecoder().decode([Item].self, from: data) {
            items = saved
        }
    }

    /// Chamado por timer: captura texto ou imagem novos, ignorando senhas (tipos "concealed").
    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        if let types = pb.types, !ignoredTypes.isDisjoint(with: types) { return }
        if let text = pb.string(forType: .string) {
            if !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { addText(text) }
        } else if let png = pngData(from: pb) {
            addImage(png)
        }
    }

    func copyToPasteboard(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let file = item.imageFile, let data = try? Data(contentsOf: imagesDir.appendingPathComponent(file)) {
            pb.setData(data, forType: .png)
        } else {
            pb.setString(item.text, forType: .string)
        }
        lastChange = pb.changeCount
        moveToTop(item)
    }

    func thumbnail(for item: Item) -> NSImage? {
        guard let file = item.imageFile else { return nil }
        if let cached = thumbnails.object(forKey: file as NSString) { return cached }
        let url = imagesDir.appendingPathComponent(file) as CFURL
        guard let source = CGImageSourceCreateWithURL(url, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
        ]
        guard let cg = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cg, size: NSSize(width: cg.width, height: cg.height))
        thumbnails.setObject(image, forKey: file as NSString)
        return image
    }

    func togglePin(_ item: Item) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
        save()
    }

    func delete(_ item: Item) {
        remove(items.filter { $0.id == item.id })
    }

    func clearUnpinned() {
        remove(items.filter { !$0.pinned })
    }

    private func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func addText(_ text: String) {
        if let existing = items.first(where: { !$0.isImage && $0.text == text }) {
            moveToTop(existing)
        } else {
            insert(Item(id: UUID(), text: text, date: Date(), pinned: false))
        }
    }

    private func addImage(_ png: Data) {
        let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        if let existing = items.first(where: { $0.imageHash == hash }) {
            moveToTop(existing)
            return
        }
        let file = "\(UUID().uuidString).png"
        do { try png.write(to: imagesDir.appendingPathComponent(file), options: .atomic) } catch { return }
        insert(Item(id: UUID(), text: "", date: Date(), pinned: false, imageFile: file, imageHash: hash))
    }

    private func moveToTop(_ item: Item) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: i)
        moved.date = Date()
        items.insert(moved, at: 0)
        save()
    }

    private func insert(_ item: Item) {
        items.insert(item, at: 0)
        var unpinned = 0
        let overflow = items.filter { item in
            if item.pinned { return false }
            unpinned += 1
            return unpinned > limit
        }
        remove(overflow)
    }

    private func remove(_ removed: [Item]) {
        let ids = Set(removed.map(\.id))
        for item in removed {
            if let file = item.imageFile {
                try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(file))
                thumbnails.removeObject(forKey: file as NSString)
            }
        }
        items.removeAll { ids.contains($0.id) }
        save()
    }

    private func save() {
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: fileURL, options: .atomic)
        }
    }
}
